/**
 * Writes packages/contracts/openapi.yaml from the live route definitions, so the spec can never
 * drift from what the server actually validates. With --check, fails if the committed file is stale.
 */
import { readFile, writeFile } from "node:fs/promises";
import { stringify } from "yaml";
import { buildApp } from "../src/app.js";

const target = new URL("../../../packages/contracts/openapi.yaml", import.meta.url);
const app = await buildApp({ readinessChecks: {}, logLevel: "silent" });
await app.ready();
const spec = `# GENERATED by apps/api/scripts/generate-openapi.ts. Do not edit by hand.\n${stringify(app.swagger(), { aliasDuplicateObjects: false })}`;
await app.close();

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== spec) {
    console.error("openapi.yaml is stale. Run `pnpm contracts:generate` and commit the result.");
    process.exit(1);
  }
  console.log("openapi.yaml is up to date");
} else {
  await writeFile(target, spec);
  console.log(`wrote ${target.pathname}`);
}
